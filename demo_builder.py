"""
demo_builder.py — turn a game concept into a runnable Godot 4 skeleton.

Takes a ``GameConcept`` (game_concept.py) and produces a Godot 4
project directory with:

  • project.godot manifest
  • A main scene (.tscn) sized to the genre (platformer / top-down /
    puzzle / VN / etc. — see ``GENRE_TEMPLATES``)
  • A main.gd script stub the player can already run
  • icon.svg placeholder so Godot doesn't yell about a missing icon
  • README.md describing the concept and the TODO list

Output lives at ``vault/projects/<slug>/`` so the user can open it
in the Godot Workspace tab and hit Run within seconds.

The skeleton is intentionally minimal — enough to launch without
errors and show *something* on screen, with TODO markers exactly
where the user (or the GodotCoder) should fill in the next layer
of detail. We do NOT try to ship a finished game here; that's the
user + Coder agent's job.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


# ============================================================
# Result type
# ============================================================

@dataclass
class DemoBuildResult:
    """Outcome of one demo build."""
    project_path:    Optional[Path] = None
    files_written:   List[Path] = field(default_factory=list)
    notes:           List[str] = field(default_factory=list)
    error:           str = ""

    @property
    def ok(self) -> bool:
        return self.project_path is not None and not self.error


# ============================================================
# Genre → skeleton template selection
# ============================================================

# Map common genre strings (case-insensitive substring match) to a
# template name. The first matching template wins. The fallback is
# "generic" — a single Node2D with a label.
GENRE_TEMPLATES: Tuple[Tuple[str, str], ...] = (
    ("platformer",       "platformer"),
    ("metroidvania",     "platformer"),
    ("puzzle-platformer","platformer"),
    ("top-down",         "topdown"),
    ("twin-stick",       "topdown"),
    ("shooter",          "topdown"),
    ("roguelike",        "topdown"),
    ("rpg",              "topdown"),
    ("visual novel",     "vn"),
    ("vn",               "vn"),
    ("walking sim",      "vn"),
    ("puzzle",           "puzzle"),
    ("deck",             "puzzle"),
    ("management",       "puzzle"),
    ("city builder",     "puzzle"),
)


def _pick_template(genre: str) -> str:
    g = (genre or "").lower()
    for needle, tpl in GENRE_TEMPLATES:
        if needle in g:
            return tpl
    return "generic"


# ============================================================
# Static assets (kept inline so demo_builder is self-contained)
# ============================================================

# Minimal valid Godot icon.svg — a tiny solid square. Avoids the
# "no icon configured" warning on first launch.
_ICON_SVG = '''<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg">
<rect width="128" height="128" fill="#d32f2f"/>
</svg>'''


def _project_godot(concept_title: str, main_scene: str) -> str:
    """Render the project.godot manifest. Format 5 is Godot 4.x."""
    return (
        "; Engine configuration file.\n"
        "; Generated by Anvil demo_builder.\n"
        "\n"
        "config_version=5\n"
        "\n"
        "[application]\n"
        f'config/name="{concept_title}"\n'
        f'run/main_scene="{main_scene}"\n'
        'config/features=PackedStringArray("4.2", "GL Compatibility")\n'
        'config/icon="res://icon.svg"\n'
        "\n"
        "[rendering]\n"
        'renderer/rendering_method="gl_compatibility"\n'
        'renderer/rendering_method.mobile="gl_compatibility"\n'
    )


# ============================================================
# Per-genre skeletons
# ============================================================
#
# Each template returns a list of (relative_path, content_string)
# pairs. Path strings use forward slashes; we normalise when writing.

def _tpl_platformer(concept) -> List[Tuple[str, str]]:
    main_tscn = (
        '[gd_scene load_steps=2 format=3]\n'
        '\n'
        '[ext_resource type="Script" path="res://main.gd" id="1_main"]\n'
        '\n'
        '[node name="Main" type="Node2D"]\n'
        'script = ExtResource("1_main")\n'
        '\n'
        '[node name="Label" type="Label" parent="."]\n'
        'offset_left = 20.0\n'
        'offset_top = 20.0\n'
        'offset_right = 400.0\n'
        'offset_bottom = 80.0\n'
        f'text = "{concept.display_title}"\n'
        '\n'
        '[node name="Floor" type="StaticBody2D" parent="."]\n'
        'position = Vector2(0, 500)\n'
        '\n'
        '[node name="Shape" type="CollisionShape2D" parent="Floor"]\n'
        '\n'
        '[node name="Player" type="CharacterBody2D" parent="."]\n'
        'position = Vector2(200, 300)\n'
        '\n'
        '[node name="Sprite" type="ColorRect" parent="Player"]\n'
        'offset_left = -16.0\n'
        'offset_top = -16.0\n'
        'offset_right = 16.0\n'
        'offset_bottom = 16.0\n'
        'color = Color(0.83, 0.18, 0.18, 1)\n'
        '\n'
        '[node name="Collision" type="CollisionShape2D" parent="Player"]\n'
    )
    main_gd = (
        '# main.gd — Platformer skeleton\n'
        f'# Concept: {concept.display_title}\n'
        f'# Genre:   {concept.genre or "Platformer"}\n'
        f'# Hook:    {concept.hook}\n'
        '\n'
        'extends Node2D\n'
        '\n'
        '@export var move_speed: float = 200.0\n'
        '@export var jump_velocity: float = -400.0\n'
        '@export var gravity: float = 980.0\n'
        '\n'
        '@onready var player: CharacterBody2D = $Player\n'
        '\n'
        'func _ready() -> void:\n'
        f'\tprint("[main] {concept.display_title} ready")\n'
        '\n'
        'func _physics_process(delta: float) -> void:\n'
        '\tvar velocity := player.velocity\n'
        '\tvelocity.y += gravity * delta\n'
        '\tvar dir := Input.get_axis("ui_left", "ui_right")\n'
        '\tvelocity.x = dir * move_speed\n'
        '\tif Input.is_action_just_pressed("ui_up") and player.is_on_floor():\n'
        '\t\tvelocity.y = jump_velocity\n'
        '\tplayer.velocity = velocity\n'
        '\tplayer.move_and_slide()\n'
        '\n'
        '# TODO mechanics — fill in from the concept:\n'
        + "\n".join(f"#   - {m}" for m in (concept.mechanics or ["(none listed)"]))
    )
    return [("project.godot", "__main_scene__"),
            ("main.tscn", main_tscn),
            ("main.gd", main_gd)]


