"""
council_qt.group_tabs — the 6-group tab layout with profile switching.

The design in TAB_CONSOLIDATION_SPEC.md: 30 top-level tabs collapse into 6
group tabs (Council, Knowledge, Agents & Models, Build, Create, Lab). Each
group holds an inner ``QTabWidget`` with its tabs; a "Show tabs ▾" button at
the group's top-right edge toggles which of them are visible. A "Show more ▾"
corner widget at the right end of the TOP-level tab bar lists every
currently-hidden tab (and group); a status-bar "Profile: X ▾" switches between
Demo / Developer / Full / Custom.

WHAT COUNCIL WILL WRITE, AND WHAT WE DO HERE
``council_qt.profiles`` holds the GROUPS mapping and the three preset constants
(DEMO, DEVELOPER, FULL). It is being generated by the Council dogfood pipeline
in a separate PR; this file imports it as data. When the module is not yet
present, the controller stays in a graceful off state and ``add_tab`` keeps
behaving like the flat shell did — nothing here fabricates placeholder groups
that would mask the Council PR.

LAZY BUILD IS PRESERVED
The window still registers tabs with a factory that runs on first show. We
insert them into the group's inner ``QTabWidget`` as placeholder widgets; the
window swaps the real widget in when the inner tab is visited. A tab hidden
by the active profile never pays its build cost.
"""
from __future__ import annotations

from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple

from PySide6.QtCore import Qt
from PySide6.QtGui import QAction
from PySide6.QtWidgets import (QHBoxLayout, QLabel, QMenu, QSizePolicy,
                               QTabWidget, QToolButton, QVBoxLayout, QWidget)


def try_import_profiles() -> Optional[Any]:
    """``council_qt.profiles``, or None if Council has not written it yet.

    Not writing fallback constants here is deliberate: the dogfood PR delivers
    GROUPS and the three preset sets, and a placeholder would mask that
    delivery. The one-line notice is printed so a launch where the file is
    missing says so rather than silently reverting to a flat shell.
    """
    try:
        from council_qt import profiles           # noqa: WPS433 (local import)
    except ImportError as exc:
        print(
            "[group_tabs] council_qt/profiles.py is missing — see "
            "COUNCIL_DOGFOOD_PROMPT.md. "
            f"({exc!r})",
            flush=True)
        return None
    return profiles


class GroupPage(QWidget):
    """One of the six top-level pages: a 'Show tabs ▾' header + inner tabs."""

    def __init__(self, name: str, parent=None):
        super().__init__(parent)
        self.group_name = name
        self._inner_tab_ids: List[str] = []     # positional ids inside .inner
        self._inner_tab_titles: Dict[str, str] = {}

        root = QVBoxLayout(self)
        root.setContentsMargins(0, 0, 0, 0)
        root.setSpacing(0)

        header = QWidget(self)
        header.setObjectName("GroupPageHeader")
        header_lay = QHBoxLayout(header)
        header_lay.setContentsMargins(6, 2, 6, 2)
        header_lay.setSpacing(4)
        header_lay.addStretch(1)
        self.show_tabs_button = QToolButton(header)
        self.show_tabs_button.setText("Show tabs ▾")
        self.show_tabs_button.setPopupMode(QToolButton.InstantPopup)
        self.show_tabs_button.setAutoRaise(True)
        self.show_tabs_button.setToolTip(
            f"Which tabs in {name} to show")
        self._menu = QMenu(self.show_tabs_button)
        self.show_tabs_button.setMenu(self._menu)
        header_lay.addWidget(self.show_tabs_button, 0, Qt.AlignRight)
        root.addWidget(header, 0)

        self.inner = QTabWidget(self)
        self.inner.setDocumentMode(True)
        self.inner.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)
        root.addWidget(self.inner, 1)

    def register_inner_tab(self, tab_id: str, title: str,
                           widget: QWidget) -> None:
        self._inner_tab_ids.append(tab_id)
        self._inner_tab_titles[tab_id] = title
        # Signals are blocked around addTab: the first add makes the tab
        # current and fires inner.currentChanged, which lazy-builds the page.
        # That is wrong at REGISTRATION time (the profile may hide this very
        # tab, and the user has not visited the group yet). The build is
        # triggered when the group becomes current, through the window's
        # top-level currentChanged.
        self.inner.blockSignals(True)
        try:
            self.inner.addTab(widget, title)
        finally:
            self.inner.blockSignals(False)

    def index_of(self, tab_id: str) -> int:
        try:
            return self._inner_tab_ids.index(tab_id)
        except ValueError:
            return -1

    def inner_tab_ids(self) -> Sequence[str]:
        return tuple(self._inner_tab_ids)

    def title_for(self, tab_id: str) -> str:
        return self._inner_tab_titles.get(tab_id, tab_id)

    def set_inner_visibility(self, visible_ids: set) -> int:
        """Show/hide inner tabs; return the number currently visible.

        The whole operation is run with signals blocked: setTabVisible on the
        current tab makes Qt shift the current index to the next visible tab,
        each shift firing currentChanged, each firing running the lazy build
        for whichever tab Qt happened to land on. The build we DO want runs
        once at the end of ``_apply``, through the window's own top-level
        currentChanged.
        """
        count = 0
        self.inner.blockSignals(True)
        try:
            bar = self.inner.tabBar()
            for pos, tab_id in enumerate(self._inner_tab_ids):
                show = tab_id in visible_ids
                try:
                    bar.setTabVisible(pos, show)
                except Exception:                         # noqa: BLE001
                    # A bar from an older Qt without setTabVisible would
                    # raise; a missing feature here is a visible defect,
                    # not fatal.
                    pass
                if show:
                    count += 1
            if count and self.inner.currentIndex() >= 0:
                if not bar.isTabVisible(self.inner.currentIndex()):
                    for pos in range(self.inner.count()):
                        if bar.isTabVisible(pos):
                            self.inner.setCurrentIndex(pos)
                            break
        finally:
            self.inner.blockSignals(False)
        return count

    def rebuild_show_tabs_menu(self, visible_ids: set,
                               on_toggle: Callable[[str, bool], None]) -> None:
        self._menu.clear()
        for tab_id in self._inner_tab_ids:
            action = QAction(self._inner_tab_titles.get(tab_id, tab_id),
                             self._menu)
            action.setCheckable(True)
            action.setChecked(tab_id in visible_ids)
            action.toggled.connect(                       # noqa: WPS437
                lambda checked, tid=tab_id: on_toggle(tid, bool(checked)))
            self._menu.addAction(action)


# ------------------------------------------------------------- the controller

class GroupedTabsController:
    """Owns the group pages, the profile machinery, and the two popup menus.

    Built once per CouncilWindow when ``council_qt.profiles`` imports. If it
    does not, the window keeps the flat shell; nothing here runs.
    """

    def __init__(self, window, profiles_module: Any) -> None:
        self.window = window
        self.profiles = profiles_module
        self.groups_order: Tuple[str, ...] = tuple(
            getattr(profiles_module, "GROUP_ORDER", None)
            or list(profiles_module.GROUPS.keys()))
        self.groups: Dict[str, GroupPage] = {}
        self._group_titles: Dict[str, str] = dict(
            getattr(profiles_module, "GROUP_TITLES", {}))
        self._id_to_group: Dict[str, str] = {}
        for name in self.groups_order:
            for tab_id in profiles_module.GROUPS[name]:
                self._id_to_group[tab_id] = name

        # The active profile and its derived state.
        self.profile_name: str = "full"
        self.custom_base: str = "demo"
        self.custom_advanced: bool = False
        self.visible_ids: set = set(self._all_known_ids())

        # The top-level widget we populate — the window's QTabWidget. Each
        # group page is a top-level tab, created up front and hidden until a
        # tab registers into it (auto-hide-empty-groups, spec §2).
        self.top_tabs = window.tabs
        for name in self.groups_order:
            page = GroupPage(name)
            self.groups[name] = page
            title = self._group_titles.get(name, name)
            self.top_tabs.addTab(page, title)
            idx = self.top_tabs.count() - 1
            self.top_tabs.tabBar().setTabVisible(idx, False)

        # The corner "Show more ▾" button.
        self.show_more_button = QToolButton(self.top_tabs)
        self.show_more_button.setText("Show more ▾")
        self.show_more_button.setPopupMode(QToolButton.InstantPopup)
        self.show_more_button.setAutoRaise(True)
        self._show_more_menu = QMenu(self.show_more_button)
        self.show_more_button.setMenu(self._show_more_menu)
        self.top_tabs.setCornerWidget(self.show_more_button,
                                      Qt.TopRightCorner)
        self.show_more_button.hide()                       # nothing hidden yet

        # The status-bar profile label. Added to the right end of the status
        # bar so it does not fight the status text that lives on the left.
        self.profile_button = QToolButton(window)
        self.profile_button.setPopupMode(QToolButton.InstantPopup)
        self.profile_button.setAutoRaise(True)
        self._profile_menu = QMenu(self.profile_button)
        self.profile_button.setMenu(self._profile_menu)
        try:
            window.statusBar().addPermanentWidget(self.profile_button, 0)
        except Exception:                                 # noqa: BLE001
            pass

        self._notice_label: Optional[QLabel] = None
        self._rebuild_profile_menu()

    # -- registration -------------------------------------------------
    def register_tab(self, tab_id: str, title: str,
                     widget: QWidget) -> Optional[GroupPage]:
        group_name = self._id_to_group.get(tab_id)
        if group_name is None:
            return None
        page = self.groups[group_name]
        page.register_inner_tab(tab_id, title, widget)
        return page

    # -- profile ------------------------------------------------------
    def apply_profile_state(self, ui_section: Dict[str, Any]) -> None:
        profile = str(ui_section.get("profile", "full")).lower()
        custom = ui_section.get("custom") or {}
        self.custom_base = str(custom.get("base_profile", "demo")).lower()
        self.custom_advanced = bool(custom.get("advanced_mode", False))
        if profile == "custom":
            self.profile_name = "custom"
            custom_ids = custom.get("visible_tabs") or []
            self.visible_ids = {str(t) for t in custom_ids
                                if t in self._id_to_group}
        else:
            self.profile_name = profile if profile in (
                "demo", "developer", "full") else "full"
            self.visible_ids = self._preset_ids(self.profile_name)
        self._apply()

    def _apply(self) -> None:
        """Refresh every page, the top-level tab bar, menus and the label."""
        bar = self.top_tabs.tabBar()
        hidden_by_group: Dict[str, List[str]] = {}
        for group_name in self.groups_order:
            page = self.groups[group_name]
            visible = page.set_inner_visibility(self.visible_ids)
            idx = self.top_tabs.indexOf(page)
            if idx >= 0:
                bar.setTabVisible(idx, visible > 0)
            page.rebuild_show_tabs_menu(self.visible_ids, self._on_toggle)
            # Any inner tab in this group not currently visible → the
            # Show-more menu.
            hidden = [tid for tid in page.inner_tab_ids()
                      if tid not in self.visible_ids]
            if hidden:
                hidden_by_group[group_name] = hidden

        self._rebuild_show_more_menu(hidden_by_group)
        self._rebuild_profile_menu()
        self._refresh_profile_label()

        # Land on the first visible top-level tab so a profile change does
        # not leave the user on an auto-hidden group.
        current = self.top_tabs.currentIndex()
        if current < 0 or not bar.isTabVisible(current):
            for i in range(self.top_tabs.count()):
                if bar.isTabVisible(i):
                    self.top_tabs.setCurrentIndex(i)
                    break

        # Lazy-build whatever inner tab is now in front: set_inner_visibility
        # ran with signals blocked, so no currentChanged reached the window
        # during the sweep. The one build we DO want is the current group's
        # visible inner tab; running it here is what makes the Council tab
        # pay its construction cost on launch and nothing else does.
        try:
            self.window._build_current_inner()           # noqa: SLF001
        except Exception as exc:                          # noqa: BLE001
            print(f"[group_tabs] lazy build after profile apply "
                  f"failed: {exc!r}", flush=True)

    # -- toggling -----------------------------------------------------
    def _on_toggle(self, tab_id: str, visible: bool) -> None:
        """User flipped a checkbox in Show tabs / Show more."""
        if visible:
            self.visible_ids.add(tab_id)
        else:
            self.visible_ids.discard(tab_id)
        if self.profile_name != "custom":
            # Spec §3.2: toggling on a preset silently flips to Custom.
            previous_base = self.profile_name
            self.profile_name = "custom"
            self.custom_base = previous_base
            self.custom_advanced = previous_base in ("developer", "full")
        self._apply()
        self._persist_current()

    def _reset_custom_to_base(self) -> None:
        if self.profile_name != "custom":
            return
        base = self.custom_base if self.custom_base in (
            "demo", "developer", "full") else "demo"
        self.profile_name = base
        self.visible_ids = self._preset_ids(base)
        self.custom_advanced = base in ("developer", "full")
        self._apply()
        self._persist_current()

    def _switch_profile(self, profile: str) -> None:
        profile = profile.lower()
        if profile == self.profile_name:
            return
        if profile in ("demo", "developer", "full"):
            self.profile_name = profile
            self.visible_ids = self._preset_ids(profile)
        elif profile == "custom":
            self.profile_name = "custom"
        else:
            return
        self._apply()
        self._persist_current()

    # -- advanced-mode layering --------------------------------------
    def advanced_mode(self) -> bool:
        if self.profile_name == "demo":
            return False
        if self.profile_name in ("developer", "full"):
            return True
        if self.profile_name == "custom":
            return self.custom_advanced
        return False

    def ui_section(self) -> Dict[str, Any]:
        return {
            "profile": self.profile_name,
            "custom": {
                "base_profile": self.custom_base,
                "advanced_mode": self.custom_advanced,
                "visible_tabs": sorted(self.visible_ids),
            },
        }

    # -- notice -------------------------------------------------------
    def show_once_notice(self, text: str) -> None:
        """The one-time nudge from spec §6."""
        try:
            self.window.set_status(text)
        except Exception:                                  # noqa: BLE001
            pass

    # -- helpers ------------------------------------------------------
    def _all_known_ids(self) -> set:
        return set(self._id_to_group)

    def _preset_ids(self, name: str) -> set:
        attr = {
            "demo": "DEMO",
            "developer": "DEVELOPER",
            "full": "FULL",
        }.get(name, "FULL")
        preset = getattr(self.profiles, attr, None)
        if preset is None:
            return set(self._id_to_group)
        return {t for t in preset if t in self._id_to_group}

    def _rebuild_show_more_menu(
            self, hidden_by_group: Dict[str, List[str]]) -> None:
        self._show_more_menu.clear()
        if not hidden_by_group:
            self.show_more_button.hide()
            return
        for group_name in self.groups_order:
            hidden = hidden_by_group.get(group_name)
            if not hidden:
                continue
            header = self._show_more_menu.addSection(
                self._group_titles.get(group_name, group_name))
            # addSection returns the action; silence lint if unused.
            del header
            for tab_id in hidden:
                page = self.groups[group_name]
                action = QAction(page.title_for(tab_id),
                                 self._show_more_menu)
                action.triggered.connect(
                    lambda _checked=False, tid=tab_id: self._on_toggle(
                        tid, True))
                self._show_more_menu.addAction(action)
        self.show_more_button.show()

    def _rebuild_profile_menu(self) -> None:
        self._profile_menu.clear()
        for key, label in (("demo", "Demo"), ("developer", "Developer"),
                           ("full", "Full"), ("custom", "Custom")):
            action = QAction(label, self._profile_menu)
            action.setCheckable(True)
            action.setChecked(self.profile_name == key)
            action.triggered.connect(
                lambda _checked=False, k=key: self._switch_profile(k))
            if key == "custom" and self.profile_name != "custom":
                # Spec §4: switching to Custom from scratch starts with what
                # the user is seeing — honoured by _switch_profile which keeps
                # visible_ids as they are.
                pass
            self._profile_menu.addAction(action)
        self._profile_menu.addSeparator()
        reset = QAction("Reset current profile", self._profile_menu)
        reset.triggered.connect(lambda _checked=False: self._reset_custom_to_base())
        reset.setEnabled(self.profile_name == "custom")
        self._profile_menu.addAction(reset)

    def _refresh_profile_label(self) -> None:
        label = {
            "demo": "Demo", "developer": "Developer",
            "full": "Full", "custom": "Custom",
        }.get(self.profile_name, self.profile_name.title())
        self.profile_button.setText(f"Profile: {label} ▾")

    def _persist_current(self) -> None:
        try:
            from . import ui_settings
            ui_settings.save_ui(self.ui_section())
        except Exception as exc:                            # noqa: BLE001
            print(f"[group_tabs] could not persist ui settings: {exc!r}",
                  flush=True)
