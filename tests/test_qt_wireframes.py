def _shape_id(stem: str, index: int) -> str:
    """A stable id for shape ``index`` of case ``stem``.

    new_shape gives a fresh uuid4 every call, so two runs of the same builder
    would write two different files and the drift test could never pass.
    uuid5 is just as unique across cases and the same on every run."""
    return uuid.uuid5(uuid.NAMESPACE_URL,
                      f"council:examples/gui/qt_tests/{stem}#{index}").hex


class _Draw:
    """One wireframe, drawn shape by shape in the order a user would: every
    container before the things inside it. z is the drawing order, which is
    what containment inference and the tab order both read."""

    def __init__(self, stem: str, project: str, title: str) -> None:
        self.stem = stem
        self.project = Project(
            project=project, mode="linked",
            canvas=Canvas(w=CANVAS_W, h=CANVAS_H, grid_snap=GRID),
            window=Window(title=title))

    def __call__(self, kind: str, x: int, y: int, w: int, h: int,
                 label: str = "", *, port=None, drives=None, bg: str = "",
                 fg: str = "", **props) -> Shape:
        s = new_shape(kind, x, y, w=w, h=h, label=label)
        s.props.update(props)
        s.port = {"name": port} if isinstance(port, str) else dict(port or {})
        s.drives = dict(drives or {})
        s.bg, s.fg = bg, fg
        index = len(self.project.shapes)
        s.id = _shape_id(self.stem, index)
        s.z = index + 1
        self.project.shapes.append(s)
        return s


BUILDERS: Dict[str, Callable[[], Project]] = {}


def _case(stem: str, project: str, title: str):
    """Register a builder: ``stem`` is the file name (its prefix the tier),
    ``project`` the name the Designer would show, ``title`` the window's."""
    def register(fn: Callable[[_Draw], None]) -> Callable[[], Project]:
        def build() -> Project:
            draw = _Draw(stem, project, title)
            fn(draw)
            return draw.project
        BUILDERS[stem] = build
        return build
    return register


