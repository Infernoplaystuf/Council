FILES = sorted(CASES_DIR.glob("*.gspec"))


def _tier(path: Path) -> str:
    return path.stem.split("_", 1)[0]


def _params(stems=None, xfail: Optional[Dict[str, str]] = None):
    """One param per case file, id'd by its stem. ``xfail`` maps a stem to why
    it still fails. strict, so the day one starts passing the run says so and
    the entry comes out — a known-failure list that cannot go stale.

    No case needs one on the core path (rules, generate, open, probe): every
    tier C case builds and behaves as its README line says."""
    out = []
    for path in FILES:
        if stems is not None and path.stem not in stems:
            continue
        why = (xfail or {}).get(path.stem)
        marks = [pytest.mark.xfail(reason=why, strict=True)] if why else []
        out.append(pytest.param(path, id=path.stem, marks=marks))
    return out


