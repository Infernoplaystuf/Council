#: Module names a generated project is imported under. Every Qt test file uses
#: the same ones, so each project forgets the previous one's first.
GENERATED = ("app", "handlers", "ui", "ui.main_ui", "ui.ports", "ui.widgets")


def _forget() -> None:
    for mod in [m for m in list(sys.modules) if m in GENERATED]:
        del sys.modules[mod]


@pytest.fixture(scope="module")
def qapp():
    """The one QApplication, offscreen. Created lazily so the rule and
    generate tests above still run where PySide6 is not installed."""
    pytest.importorskip("PySide6", reason="PySide6 is not installed in this "
                                          "interpreter")
    from PySide6.QtWidgets import QApplication
    app = QApplication.instance() or QApplication([])
    yield app
    app.processEvents()


class Live:
    """A generated case, running: the App plus a way to find a shape's widget
    by what the case called it (its label, or the port name it declared)."""

    def __init__(self, ui, project: Project, pdir: Path, qapp,
                 tmp: Path) -> None:
        self.ui, self.project, self.pdir, self.qapp = ui, project, pdir, qapp
        self.tmp = tmp                       # scratch space for a probe
        self.names = gui_projects.load_manifest(pdir).widget_names

    def shape(self, label: str = "", *, port: str = "", kind: str = ""
              ) -> Shape:
        found = [s for s in self.project.shapes
                 if (not label or s.label == label)
                 and (not port or s.port.get("name") == port)
                 and (not kind or s.kind == kind)]
        assert len(found) == 1, (label, port, kind, len(found))
        return found[0]

    def widget(self, label: str = "", *, port: str = "", kind: str = ""):
        return getattr(self.ui, self.names[self.shape(label, port=port,
                                                      kind=kind).id])

    def record(self, handler: str) -> list:
        """Capture calls to ``handler``. Set on the INSTANCE: _command and
        _EventPort look the name up at the moment of the click, which is the
        contract handlers.py is written against, so an instance attribute is
        reached exactly as a HandlerMixin method would be."""
        calls: list = []
        setattr(self.ui, handler, lambda *args: calls.append(args))
        return calls

    def handler_of(self, label: str = "", *, port: str = "") -> str:
        return "on_" + self.names[self.shape(label, port=port).id]

    def main_ui(self) -> str:
        return (self.pdir / "ui" / "main_ui.py").read_text(encoding="utf-8")

    def settle(self, done: Callable[[], bool], seconds: float = 5.0) -> bool:
        """Run the event loop until ``done()`` or the deadline. The frame
        browser debounces with QTimers, so a single processEvents is not
        enough to see a folder load or a scrub land."""
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            self.qapp.processEvents()
            if done():
                return True
            time.sleep(0.02)
        return done()


@contextmanager
def _opened(path: Path, tmp_path: Path, qapp):
    """Generate a case and construct its App the way main() does, offscreen,
    shown at the Designer's canvas size."""
    project, pdir, result = _generate(path, tmp_path / "vault")
    assert result.ok, result.lines
    _forget()
    sys.path.insert(0, str(pdir))
    ui = None
    try:
        from app import App
        ui = App()
        ui.resize(CANVAS_W, CANVAS_H)
        ui.show()
        qapp.processEvents()
        yield Live(ui, project, pdir, qapp, tmp_path)
    finally:
        if ui is not None:
            ui.request_close()
            qapp.processEvents()
        if str(pdir) in sys.path:
            sys.path.remove(str(pdir))
        _forget()


def _under_a_notebook(shape: Shape, shapes: List[Shape]) -> bool:
    box = container_of(shape, shapes)
    while box is not None:
        if box.kind == "notebook":
            return True
        box = container_of(box, shapes)
    return False


@pytest.mark.parametrize("path", _params())
def test_a_case_opens_as_a_qt_window_with_every_shape_where_it_was_drawn(
        path, tmp_path, qapp):
    """Construct, show, and check the window against the drawing:

      * every shape is a live widget on the App, under the container it was
        drawn inside (a tab page is reparented into the tab widget's stack,
        so "under" is isAncestorOf, not parentWidget)
      * every port the manifest recorded is declared on ui.ports
      * every widget that fires a callback has its on_<name> to reach
      * everything not tucked behind a notebook tab is on screen with a size
    """
    from PySide6.QtWidgets import QWidget
    with _opened(path, tmp_path, qapp) as live:
        ui, shapes = live.ui, live.project.shapes
        assert ui.isVisible()
        for s in shapes:
            name = live.names[s.id]
            widget = getattr(ui, name)
            assert isinstance(widget, QWidget), name
            box = container_of(s, shapes)
            holder = ui if box is None else getattr(ui, live.names[box.id])
            assert holder.isAncestorOf(widget), (
                f"{name} is not inside {holder.objectName() or holder}")
            if s.kind in COMMAND_KINDS:
                assert callable(getattr(ui, f"on_{name}", None)), name
            if not _under_a_notebook(s, shapes):
                assert widget.isVisible(), f"{name} is not on screen"
                assert widget.width() > 0 and widget.height() > 0, name
        declared = set(ui.ports._names)
        for port in gui_projects.load_manifest(live.pdir).port_names.values():
            assert port in declared, port


