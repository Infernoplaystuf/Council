#: What README.md writes on a case's line for a loss pinned above.
KNOWN_LOSS = "**Known Qt loss (strict xfail):**"


def test_the_readme_names_exactly_the_losses_pinned_as_strict_xfails():
    """The strict xfails above cannot go stale — an XPASS fails the run — but
    the README line describing each one could, and did: three lines still
    said "Known Qt loss (strict xfail)" for b_single_child_containers,
    c_menubar_dicts and c_colour_no_caps's 1100x780 window after all three
    were fixed, and the one loss still pinned — c_colour_no_caps's empty
    notebook, Empty tabs — was described nowhere. So the marked cases must be
    exactly the pinned ones, and a DRAWN_SHARE loss must name its shape."""
    lines = {m.group(1): ln for ln in README.read_text(
        encoding="utf-8").splitlines()
        for m in [re.search(r"^\| `([a-c]_[a-z0-9_]+)\.gspec`", ln)] if m}
    pinned = {stem for stem, _sel, _least, why in DRAWN_SHARE if why}
    pinned |= set(TOO_BIG)
    marked = {stem for stem, ln in lines.items() if KNOWN_LOSS in ln}
    assert marked == pinned, (f"marked in README but not pinned: "
                              f"{sorted(marked - pinned)}; pinned but not "
                              f"marked: {sorted(pinned - marked)}")
    for stem, selector, _least, why in DRAWN_SHARE:
        if why:
            loss = lines[stem].split(KNOWN_LOSS, 1)[1]
            for value in selector.values():
                assert str(value) in loss, (stem, value)


