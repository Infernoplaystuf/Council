def _assert_packed(child, holder) -> None:
    """``child`` is its holder's sole child the way Tk packs one: it reaches
    every edge, standing off the far right and bottom by exactly the margin
    it stands off the left.

    Stated as the gaps, not as a share of the holder or as the layout's rect,
    and both of those were tried first. "80% of the holder" failed on a 66x66
    frame whose 40x40 child filled it exactly: 26 px of frame and margin is
    40% of a box that small. The layout's contentsRect() came back as
    QRect(9, 9, -18, -18) for the freeform area — a null geometry — while the
    button inside sat correctly at (11, 11, 80, 20) in its 102x42 area. The
    gaps depend on nothing but where the child actually is. The top gap is
    not compared: a group box's title sits there. Whether the HOLDER keeps a
    sensible size is a separate question, asked by
    test_a_drawn_panel_keeps_its_share_of_the_window.
    """
    g = child.geometry()
    left = g.x()
    right = holder.width() - g.x() - g.width()
    bottom = holder.height() - g.y() - g.height()
    assert child.parentWidget() is holder
    assert left <= MARGIN and abs(right - left) <= 1 \
        and abs(bottom - left) <= 1, (
            f"child at {g} in a {holder.width()}x{holder.height()} holder: "
            f"left {left}, right {right}, bottom {bottom}")


