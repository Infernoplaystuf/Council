def _trigger_menu(menubar, *path) -> None:
    """Trigger the menu item at a title path, holding every wrapper on the
    way. Measured in test_gui_emit_qt_kinds.py: letting the parent action's
    wrapper go had PySide6 invalidate the leaf ("Internal C++ object already
    deleted") while the C++ action lived on — a test artefact, not a dead
    menu item."""
    held, actions = [], menubar.actions()
    for i, title in enumerate(path):
        found = next(a for a in actions if a.text() == title)
        held.append(found)
        if i == len(path) - 1:
            found.trigger()
            return
        held.append(found.menu())
        actions = held[-1].actions()


