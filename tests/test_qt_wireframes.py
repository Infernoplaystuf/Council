"""
Ready-made Qt wireframes, each built as a real Qt project and opened.

WHY THESE EXIST
---------------
Until now the Qt target was proven on ONE wireframe: test_gui_qt_runtime.py
drives image_viewer, and test_gui_emit_qt_kinds.py builds one or two shapes at
a time. Every defect the Qt emitter fix just closed lived in the space between
those — a combination nobody had drawn:

  * a window whose only shape is a frame, or a container holding exactly one
    widget, died in MainUi._build with "QGridLayout.addLayout(): not enough
    arguments" (gui_layout packs a sole child; the emitter spelled pack with a
    box-layout overload QGridLayout does not have)
  * a menubar whose menus were a list of titles killed emit itself with
    "'str' object has no attribute 'get'"
  * ANY window with a radiobutton died inside Ports(self), because _RadioPort
    set an attribute its __slots__ did not name

None of those needs an unusual wireframe. A login form, a tabbed settings
dialog, a split browser — the first things anyone draws — each walked into one.
So this suite is a shelf of ordinary wireframes, in tiers, and every one goes
through the WHOLE path a user's does: the .gspec on disk -> a Qt project in a
vault -> council_core.designer_project.generate (the Designer's own Generate)
-> the policy gate -> every file compiles -> App() constructed offscreen and
shown.

THE TIERS
---------
  a_*  kinds the Qt runtime is already proven on (labels, entries, buttons, a
       listbox, and the image viewer's folder -> scrubber -> canvas link)
  b_*  what the emitter fix made work: toolbar, status bar, splitters, tabs,
       group boxes, radio groups, nested and single-child containers
  c_*  edges the Qt target degrades on by design — a menubar spelled two ways,
       a fractional scale QSlider cannot hold, colour on kinds that cannot
       take it. Each must still build; where the degradation is deliberate,
       the probe checks it degrades the way the generated code says it does.

The tier is the file-name prefix, so it is visible in a folder listing and
cannot drift from a table kept somewhere else.

WHY THE .gspec FILES ARE GENERATED BY CODE IN THIS FILE
-------------------------------------------------------
A hand-typed wireframe is where a 4 px overlap, a child 2 px outside its frame
or a notebook with three pages and two tab titles comes from — and each of
those makes layout inference fall back or re-parent, so the case would test
the fallback instead of the widget. The builders below place every shape on
the 8 px grid, inside its container with a 16 px margin, containers first; the
rule check then re-proves that from the file on disk, and a drift test fails if
the file and its builder ever disagree. To change a case, edit its builder and
rewrite the files:

    python -m tests.test_qt_wireframes --write

WHY A SUBFOLDER
---------------
gui_examples.names() globs examples/gui/*.gspec NON-recursively, and whatever
it returns can be fed to a designing model as a worked example. These are test
fixtures, several deliberately degraded, and teaching a model from a menubar
spelled as a bare list of strings would be teaching it the edge case. One test
below pins that they stay out.
"""
