#: Tier C cases that break a rule ON PURPOSE, by rule name. A case listed here
#: must break exactly these rules: an edge case that stopped bending its rule
#: has stopped testing the edge.
BENDS: Dict[str, set] = {
    "c_float_scale": {"whole numbers"},
}

_NUMERIC_BOUNDS = ("from_", "to", "increment")


def container_of(shape: Shape, shapes: List[Shape]) -> Optional[Shape]:
    """The smallest container that fully contains ``shape``, or None.

    Worked out from the drawing alone, not from gui_layout: the point of the
    running-window check is that what was drawn inside what ends up inside it,
    and asking the layout engine which parent it picked would make that
    circular."""
    best = None
    for c in shapes:
        if c is shape or not is_container(c.kind) or c.area <= shape.area:
            continue
        if c.contains(shape) and (best is None or c.area < best.area):
            best = c
    return best


def rule_breaks(p: Project) -> List[Tuple[str, str]]:
    """(rule, message) for everything in ``p`` a case may not do."""
    out: List[Tuple[str, str]] = []

    def brk(rule: str, message: str) -> None:
        out.append((rule, message))

    if (p.canvas.w, p.canvas.h, p.canvas.grid_snap) != (CANVAS_W, CANVAS_H,
                                                        GRID):
        brk("canvas", f"canvas is {p.canvas.w}x{p.canvas.h} snap "
                      f"{p.canvas.grid_snap}, not the Designer's 1100x700/8")
    if not _PROJECT_NAME.match(p.project):
        brk("name", f"project name {p.project!r} cannot be a project "
                    f"directory")
    if p.gspec_version != required_version(p):
        brk("version", f"gspec_version {p.gspec_version} but the content "
                       f"needs {required_version(p)}")
    if not isinstance(p.requires, list) or any(
            str(r).split(".")[0] == "PySide6" for r in p.requires):
        brk("requires", f"requires {p.requires!r}: a Qt project gets PySide6 "
                        f"from its target, and the gate refuses declaring it")
    for chan in ("bg", "fg"):
        v = getattr(p.window, chan)
        if v and not _HEX.match(v):
            brk("colour", f"window {chan} {v!r} is not #rrggbb")

    zs = [s.z for s in p.shapes]
    if any(a >= b for a, b in zip(zs, zs[1:])):
        brk("order", f"z must increase in file order, got {zs}")

    # Up front, so a shape that fails an early check below still has its
    # container — otherwise it reads as a root shape and adds a false overlap.
    parent = {s.id: container_of(s, p.shapes) for s in p.shapes}
    for s in p.shapes:
        where = f"{s.kind} {s.label or s.port.get('name') or s.id[:8]!r}"
        if s.kind not in PALETTE or s.kind == GENERIC_KIND:
            brk("kind", f"{where}: not a concrete palette kind")
            continue
        if s.w <= 0 or s.h <= 0 or any(v % GRID for v in (s.x, s.y, s.w, s.h)):
            brk("grid", f"{where}: ({s.x}, {s.y}, {s.w}, {s.h}) is off the "
                        f"{GRID} px grid")
        if s.x < 0 or s.y < 0 or s.x2 > CANVAS_W or s.y2 > CANVAS_H:
            brk("inside canvas", f"{where}: reaches outside the canvas")
        for chan in ("bg", "fg"):
            v = getattr(s, chan)
            if v and not _HEX.match(v):
                brk("colour", f"{where}: {chan} {v!r} is not #rrggbb")

        schema = PALETTE[s.kind].get("prop_schema") or {}
        for key, value in s.props.items():
            if key not in schema:
                brk("props", f"{where}: {s.kind} has no prop {key!r}")
                continue
            choices = schema[key].get("choices")
            if choices and value not in choices:
                brk("props", f"{where}: {key}={value!r} not in {choices}")
            if schema[key].get("type") == "list[str]" and not (
                    isinstance(value, list)
                    and all(isinstance(v, str) for v in value)):
                brk("lists", f"{where}: {key} must be a real list of str, "
                             f"got {value!r}")
        if s.kind == "label" and s.props.get("anchor", "w") not in (
                "w", "center", "e"):
            brk("anchor", f"{where}: label anchor must be w, center or e")
        if s.kind in ("spinbox", "scale", "scrubber"):
            for key in _NUMERIC_BOUNDS:
                v = s.props.get(key)
                if key in s.props and (isinstance(v, bool)
                                       or not isinstance(v, int)):
                    brk("whole numbers", f"{where}: {key}={v!r} is not a "
                                         f"whole number")

        for other in p.shapes:
            if (other is not s and not is_container(other.kind)
                    and other.area > s.area and other.contains(s)):
                brk("containment", f"{where}: drawn inside a {other.kind}, "
                                   f"which cannot hold children")
        box = parent[s.id]
        if box is not None:
            gap = min(s.x - box.x, s.y - box.y, box.x2 - s.x2, box.y2 - s.y2)
            if gap < MARGIN:
                brk("margin", f"{where}: only {gap} px inside its {box.kind}; "
                              f"needs {MARGIN}")
            if box.z >= s.z:
                brk("order", f"{where}: drawn before its {box.kind}")

    siblings: Dict[Optional[str], List[Shape]] = defaultdict(list)
    for s in p.shapes:
        box = parent.get(s.id)
        siblings[box.id if box else None].append(s)
    for group in siblings.values():
        for i, a in enumerate(group):
            for b in group[i + 1:]:
                if a.overlaps(b):
                    brk("overlap", f"{a.kind} {a.label!r} and {b.kind} "
                                   f"{b.label!r} overlap")
    for s in p.shapes:
        if s.kind == "notebook":
            tabs = s.props.get("tabs") or []
            pages = siblings.get(s.id, [])
            if len(tabs) != len(pages):
                brk("tabs", f"notebook {s.label!r}: {len(pages)} page(s) but "
                            f"{len(tabs)} tab title(s)")
    return out


