def _share_params():
    out = []
    for stem, selector, least, why in DRAWN_SHARE:
        marks = [pytest.mark.xfail(reason=why, strict=True)] if why else []
        what = "-".join(str(v) for v in selector.values())
        out.append(pytest.param(stem, selector, least, marks=marks,
                                id=f"{stem}:{what}"))
    return out


@pytest.mark.parametrize("stem, selector, least", _share_params())
def test_a_drawn_panel_keeps_its_share_of_the_window(stem, selector, least,
                                                     tmp_path, qapp):
    """With the window at the size it was drawn on, a panel keeps at least
    ``least`` of its drawn width AND height. See DRAWN_SHARE for each entry's
    threshold and, where Qt falls short, the measured reason."""
    path = CASES_DIR / f"{stem}.gspec"
    with _opened(path, tmp_path, qapp) as live:
        shape = live.shape(**selector)
        widget = live.widget(**selector)
        share = (widget.width() / shape.w, widget.height() / shape.h)
        assert min(share) >= least, (
            f"drawn {shape.w}x{shape.h}, got {widget.width()}x"
            f"{widget.height()} — {share[0]:.2f} x {share[1]:.2f} of it")


